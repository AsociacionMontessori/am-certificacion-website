const assert = require('node:assert/strict')
const { BUEN_FIN, BUEN_FIN_OFFERS, getQuarterlyCampaigns, getActiveCampaign, isBuenFinActive, getNextBuenFinBoundary, getServerTime, getCampaignLabel, getCampaignTerms, getOfferMessage } = require('../src/data/buenFin2026')
assert.equal(isBuenFinActive(BUEN_FIN.start - 1), false)
assert.equal(isBuenFinActive(BUEN_FIN.start), true)
assert.equal(isBuenFinActive(Date.parse('2026-11-09T17:10:00-06:00')), true, 'No old preview expiry')
assert.equal(isBuenFinActive(Date.parse('2026-11-12T00:00:00-06:00')), true)
assert.equal(isBuenFinActive(BUEN_FIN.end - 1), true)
assert.equal(isBuenFinActive(BUEN_FIN.end), false)
assert.equal(getNextBuenFinBoundary(BUEN_FIN.start), BUEN_FIN.end)
assert.equal(getNextBuenFinBoundary(BUEN_FIN.end), Date.parse('2027-02-09T00:00:00-06:00'))
for (const year of [2027,2028,2030]) {
  const campaigns = getQuarterlyCampaigns(year)
  assert.equal(campaigns.length,4)
  for (const campaign of campaigns) {
    assert.equal(campaign.end - campaign.start, 7*24*60*60*1000)
    assert.equal(isBuenFinActive(campaign.start - 1),false)
    assert.equal(isBuenFinActive(campaign.start),true)
    assert.equal(isBuenFinActive(campaign.end - 1),true)
    assert.equal(isBuenFinActive(campaign.end),false)
    assert.equal(getNextBuenFinBoundary(campaign.start),campaign.end)
    assert.equal(getActiveCampaign(campaign.start).name,'Promoción trimestral')
    assert.ok(!getOfferMessage(BUEN_FIN_OFFERS[0],campaign).includes('Buen Fin 2026'))
    assert.ok(getOfferMessage(BUEN_FIN_OFFERS[0],campaign).includes(String(year)))
    assert.ok(getCampaignLabel(campaign).includes('15 de'))
  }
  assert.equal(getNextBuenFinBoundary(campaigns[3].end),getQuarterlyCampaigns(year+1)[0].start)
}
for (const time of [NaN,null,undefined,'2027-02-09']) {
  assert.equal(isBuenFinActive(time),false)
  assert.equal(getNextBuenFinBoundary(time),null)
}
assert.equal(getServerTime('Fri, 13 Nov 2026 06:00:00 GMT','12'),Date.parse('2026-11-13T06:00:12Z'))
for (const date of [null,'','garbage']) assert.equal(getServerTime(date),null)
assert.equal(getServerTime('Fri, 13 Nov 2026 06:00:00 GMT','-1'),null)
assert.match(getCampaignTerms(BUEN_FIN),/9 de noviembre de 2026 a las 16:40/)
assert.deepEqual(BUEN_FIN_OFFERS.map(o=>o.price),['$3,900','$3,500','$4,500'])
console.log('PASS: immediate campaign, quarterly recurrence across years, exact boundaries, server clock, labels and prices')
